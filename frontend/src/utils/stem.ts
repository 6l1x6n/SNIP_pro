/** Нижний регистр + ё→е. */
export function normLower(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е");
}

/** Стемминг одного слова (цифры не трогаем). */
export function stemWord(raw: string): string {
  const w = normLower(raw);
  if (/^\d+$/.test(w)) return w;
  for (const suf of SUFFIXES) {
    if (w.endsWith(suf) && w.length - suf.length >= 3) {
      return w.slice(0, -suf.length);
    }
  }
  return w;
}

/** Полный токенизатор 1-в-1 как build_index.py (включая цифры и слово→цифра). */
export function tokenize(text: string): string[] {
  const out: string[] = [];
  for (const raw of normLower(text).match(TOKEN_RE) ?? []) {
    if (STOPWORDS.has(raw)) continue;
    // цифры — граждане первого класса: «7» индексируется, а не только эмбеддится
    if (/^\d+$/.test(raw)) {
      out.push(raw);
      continue;
    }
    if (raw.length < 2) continue;
    const card = CARDINAL_WORDS[raw];
    if (card !== undefined) {
      out.push(String(card));
      continue;
    }
    const w = stemWord(raw);
    const ord = ORDINAL_STEMS[w];
    if (ord !== undefined) {
      out.push(String(ord));
      continue;
    }
    if (w.length >= 2 && !STOPWORDS.has(w)) out.push(w);
  }
  return out;
}

/** Значимые слова для анкоров: токены длиной ≥3 без стоп-слов (цифры отбрасываем). */
export function sigWords(text: string, minLen = 3): string[] {
  return tokenize(text).filter((w) => w.length >= minLen && !/^\d+$/.test(w));
}
